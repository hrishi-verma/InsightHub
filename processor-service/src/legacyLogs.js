// Legacy `logs` pipeline (fed by /api/logs). Kept working as before, in its own consumer group.
// Changes from the original: config comes from config.js (no defaults for secrets), the ML call
// has a real timeout, and errors are logged without message content.

// Step 1: Normalize log structure
function normalizeLog(rawLog) {
  return {
    service: rawLog.service || 'unknown',
    level: String(rawLog.level || 'INFO').toUpperCase(),
    message: rawLog.message || '',
    latency_ms: parseInt(rawLog.latency_ms) || null,
    userId: rawLog.userId || null,
    metadata: rawLog.metadata || {}
  };
}

// Step 2: Add timestamps and IDs (ID is auto-generated by DB)
function addTimestamp(log) {
  return {
    ...log,
    created_at: log.timestamp || new Date().toISOString()
  };
}

// Step 3: Convert to time-series compatible structure
function convertToTimeSeries(log) {
  return {
    ...log,
    // Ensure timestamp is in ISO format for TimescaleDB
    created_at: new Date(log.created_at).toISOString(),
    // Add time bucket for aggregations (optional)
    time_bucket: new Date(log.created_at).toISOString().slice(0, 16) + ':00.000Z'
  };
}

// Step 4: Call ML engine for anomaly scoring
async function getAnomalyScore(log, mlEngineUrl) {
  // Try ML engine API first
  if (mlEngineUrl) {
    try {
      const response = await fetch(new URL('/score', mlEngineUrl), {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          service: log.service,
          level: log.level,
          message: log.message,
          latency_ms: log.latency_ms
        }),
        redirect: 'error',
        signal: AbortSignal.timeout(2000)
      });

      if (response.ok) {
        const result = await response.json();
        if (typeof result.anomaly_score === 'number') return result;
      }
    } catch {
      // fall through to heuristics
    }
  }

  // Fallback to heuristic-based scoring
  let score = 0;

  // High latency detection
  if (log.latency_ms && log.latency_ms > 1000) {
    score += 0.5;
  }

  // Error level detection
  if (log.level === 'ERROR') {
    score += 0.3;
  }

  // Critical latency
  if (log.latency_ms && log.latency_ms > 2000) {
    score += 0.3;
  }

  return {
    anomaly_score: Math.min(score, 1.0),
    // Mark as anomaly if score exceeds threshold
    is_anomaly: score >= 0.7,
    method: 'heuristic_fallback'
  };
}

// Step 5: Store in database
async function storeLog(pool, log, anomalyData) {
  const result = await pool.query(
    `INSERT INTO logs (service, level, message, latency_ms, anomaly_score, is_anomaly, created_at)
     VALUES ($1, $2, $3, $4, $5, $6, $7)
     RETURNING log_id`,
    [
      log.service,
      log.level,
      log.message,
      log.latency_ms,
      anomalyData.anomaly_score,
      anomalyData.is_anomaly,
      log.created_at
    ]
  );
  return result.rows[0].log_id;
}

async function processLog(pool, rawLog, mlEngineUrl) {
  const timeSeries = convertToTimeSeries(addTimestamp(normalizeLog(rawLog)));
  const anomalyData = await getAnomalyScore(timeSeries, mlEngineUrl);
  return storeLog(pool, timeSeries, anomalyData);
}

async function runLegacyConsumer({ kafka, pool, mlEngineUrl, log }) {
  const consumer = kafka.consumer({ kafkaJS: { groupId: 'log-processors', fromBeginning: false } });
  await consumer.connect();
  await consumer.subscribe({ topics: ['logs'] });
  await consumer.run({
    eachMessage: async ({ message }) => {
      try {
        const rawLog = JSON.parse(message.value.toString());
        if (rawLog === null || typeof rawLog !== 'object') throw new TypeError('not an object');
        await processLog(pool, rawLog, mlEngineUrl);
      } catch (error) {
        // Continue processing other messages. Name/code only: JSON errors quote the input.
        log('legacy_log_failed', { error: error && error.name, code: error && error.code });
      }
    }
  });
  return consumer;
}

module.exports = { runLegacyConsumer, processLog };
